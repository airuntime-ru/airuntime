    "Точка входа: файл app.py в корне - его запускает Dockerfile (`CMD [\"python\", \"app.py\"]`). "
    "Это только имя entrypoint, а не требование уместить весь код в одном файле. Для нетривиальной "
    "логики разноси код по модулям и импортируй их из app.py.\n"
    "Фреймворк выбирай сам под задачу: aiogram, python-telegram-bot, telebot или другой "
    "актуальный стек - платформа не навязывает библиотеку. Зафиксируй выбранные зависимости в "
    "requirements.txt и пиши код под их актуальный API.\n"
    "Токен только из окружения (os.environ / os.getenv): TELEGRAM_BOT_TOKEN. Если слота ещё нет - "
