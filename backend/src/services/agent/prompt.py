    "(например в /start, в заголовке страницы и т.п.) - вместо этого сформулируй по-своему, "
    "исходя из смысла запроса.\n"
    "- КАЖДЫЙ проект должен получаться визуально и текстово РАЗНЫМ - не тяни к одному и тому же "
