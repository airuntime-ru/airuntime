"""System prompt for the coding agent, per project type."""

from __future__ import annotations

from src.db.models.project import Project

_WEBSITE_RULES = (
    "Точка входа сайта: public/index.html (обязательный файл). Опционально CSS/JS рядом, "
    "Dockerfile (если не создашь - платформа подставит nginx). Сайт должен открываться из "
    "public/ как статика или через твой backend - как требует задача пользователя.\n"
    "Если пользователь просит авторизацию, кабинет, API, БД - реализуй по-настоящему, не "
    "имитируй фронтом. Для данных по умолчанию достаточно SQLite в контейнере; если нужна "
    "Postgres/Redis/очередь/воркер - вызови request_service (для postgres/redis/mysql/mongo/"
    "rabbitmq достаточно kind; для остального укажи image). Не пиши docker-compose.yml и не "
    "предполагай, что внешний сервис уже есть - только через request_service.\n"
    "Визуал: сделай качественно под задачу и тон запроса пользователя. Не копируй один и тот "
    "же шаблон из проекта в проект."
)

